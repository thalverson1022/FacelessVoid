const fs = require('node:fs');
const path = require('node:path');
const read = p => JSON.parse(fs.readFileSync(path.join(__dirname, p), 'utf8'));
const icons = read('data/icon-catalog.json').map(i => ({...i, path:i.path?.replace('../../../', '../../') ?? null}));
const data = {empty:read('templates/empty-tree.json'), example:read('examples/assassin-sketch.json'), schema:read('schema/tree-lab-v1.schema.json'), icons};
const output = '/* Generated by build-data.js. Edit the JSON sources. */\nwindow.TreeLabData = '+JSON.stringify(data,null,2)+';\n';
const target = path.join(__dirname,'data/bundle.js');
if(process.argv.includes('--check')) {
  if(fs.readFileSync(target,'utf8')!==output) throw Error('Tree Lab bundle is stale. Run node tools/tree-lab/build-data.js');
  console.log('PASS generated data parity');
} else fs.writeFileSync(target,output);
