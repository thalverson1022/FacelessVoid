// Read-only draft inspection; --write refreshes only the generated audit appendix.
// Tree Lab validation/preview arithmetic is evidence, not approved gameplay policy.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../..');
const lab = require('../tree-lab/model.js');
const read = p => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const schema = read('tools/tree-lab/schema/tree-lab-v1.schema.json');
const icons = read('tools/tree-lab/data/icon-catalog.json');
const files = ['Assassin', 'Bladedancer', 'Shadow', 'Thief'];
const out = ['# P6M2-T2 Draft Inventory Appendix', '',
  'Generated by `node tools/p6/audit_tree_drafts.js --write`. Do not edit manually.', '',
  'See [the audit](P6M2_T2_Cross_Tree_Draft_Audit.md) for runtime classifications, questions, and scope.', '',
  'Rank values below use Tree Lab arithmetic: rank_1 + (rank - 1) * per_rank. They are total displayed values, not cumulative sums and not approved runtime rules. Costs are absent from these exports; one point per rank is only the lab convention. Original JSON objects preserve every field and exact text (JSON escapes encode whitespace).', ''];
const identities = new Map();
const summaries = [];
function register(kind, id, name, file) {
  const key = kind + ':' + id;
  if (!identities.has(key)) identities.set(key, []);
  identities.get(key).push({file, name});
}
function object(title, pointer, value) {
  out.push('### ' + title, '', 'JSON pointer: `' + pointer + '`', '', '```json', JSON.stringify(value, null, 2), '```', '');
}
for (const [index, name] of files.entries()) {
  const file = 'docs/talent_tree_drafts/' + name + '.json';
  const bytes = fs.readFileSync(path.join(root, file));
  const data = JSON.parse(bytes.toString('utf8'));
  const tree = data.tree;
  const hash = crypto.createHash('sha256').update(bytes).digest('hex');
  const validation = lab.validate(data, schema, icons);
  const ranks = tree.talents.reduce((n, t) => n + t.max_ranks, 0);
  const prefix = ['A', 'B', 'S', 'T'][index];
  register('tree', tree.id, tree.name, name);
  out.push('## ' + name, '', 'Source: [' + name + '.json](talent_tree_drafts/' + name + '.json)', '',
    'SHA-256: `' + hash + '`', '',
    'Format: `' + data.format + '`; schema version: `' + data.schema_version + '`.', '',
    'Tree ID: `' + tree.id + '`; subclass: `' + tree.subclass + '`.', '',
    'Notes (exact JSON string): `' + JSON.stringify(tree.notes) + '`', '',
    `${tree.talents.length} talents; ${ranks} rank slots; ${tree.automatic_unlocks.filter(u => u.skill).length} populated automatic unlocks; ${tree.talents.filter(t => t.skill_grant).length} talent skill grants.`, '',
    'Repository Tree Lab validator: ' + validation.errors.length + ' errors, ' + validation.warnings.length + ' warnings.', '');
  for (const message of [...validation.errors, ...validation.warnings]) out.push('- ' + message);
  out.push('');
  object(prefix + '-G — levels and investment gates', '/tree/levels', tree.levels);
  object(prefix + '-I — intrinsic', '/tree/intrinsic', tree.intrinsic);
  for (const [i, talent] of tree.talents.entries()) {
    const label = `${prefix}-T${String(i + 1).padStart(2, '0')}`;
    register('talent', talent.id, talent.name, name);
    object(label + ' — ' + talent.name, '/tree/talents/' + i, talent);
    if (talent.skill_grant) register('skill', talent.skill_grant.id, talent.skill_grant.name, name);
    if (talent.values.length) {
      out.push('| Value ID | Label / unit | Values at ranks 1–' + talent.max_ranks + ' |', '| --- | --- | --- |');
      for (const v of talent.values) out.push('| `' + v.id + '` | ' + (v.label + ' / ' + v.unit).replaceAll('|', '\\|') + ' | ' + Array.from({length:talent.max_ranks}, (_, r) => lab.rankValue(v, r + 1)).join(', ') + ' |');
      out.push('');
    } else out.push('No structured rank values; mechanics and constants exist only in prose.', '');
  }
  for (const [i, unlock] of tree.automatic_unlocks.entries()) {
    object(`${prefix}-U${i + 1} — ${unlock.skill ? unlock.skill.name : 'Unassigned slot'}`, '/tree/automatic_unlocks/' + i, unlock);
    if (unlock.skill) register('skill', unlock.skill.id, unlock.skill.name, name);
  }
  summaries.push({name, sha256:hash, talents:tree.talents.length, ranks, automaticSkills:tree.automatic_unlocks.filter(u=>u.skill).length, talentSkills:tree.talents.filter(t=>t.skill_grant).length, prerequisites:tree.talents.reduce((n,t)=>n+t.prerequisite_ids.length,0), ...validation});
}
out.push('## Cross-file identity collisions', '', 'Level and unlock slot IDs are local structural IDs and excluded here. Repeated entity IDs below must be scoped or remapped before combined runtime conversion.', '');
const collisions = [...identities].filter(([, entries]) => entries.length > 1);
for (const [key, entries] of collisions) out.push('- `' + key + '`: ' + entries.map(x => x.file + ' / ' + x.name).join('; '));
out.push('');
const output = out.join('\n');
const target = path.join(root, 'docs/P6M2_T2_Draft_Inventory_Appendix.md');
if (process.argv.includes('--write')) fs.writeFileSync(target, output);
else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
  console.error('Audit appendix missing or stale; regenerate with --write.');
  process.exitCode = 1;
}
if (summaries.some(x=>x.errors.length)) process.exitCode = 1;
console.log(JSON.stringify({summaries, collisions}, null, 2));
