"""Install the reviewed export as named PNGs and a generated Godot icon table.
Run from any directory. The approved source catalog is immutable provenance.
Does not change gameplay identities, resources, saves or content readiness.
"""
from pathlib import Path
import base64, hashlib, io, json, re
from PIL import Image
from reviewed_icon_treatment import apply_treatment

ROOT = Path(__file__).resolve().parents[2]
LAB = ROOT / 'tools/icon-lab'
BUFF_SOURCES = {
    'buff.footwork': 'talent.bladedancer.fancy_footwork',
    'buff.readiness': 'skill.parry_strike',
    'buff.precision': 'talent.bladedancer.precision_attacks',
    'buff.dance': 'skill.dance_of_death',
    'buff.bypass': 'talent.assassin.bypass',
    **{'buff.'+s: 'skill.'+s for s in ['virulent_poison', 'master_of_poisons', 'touch_of_darkness', 'beguiling_presence']},
}

def main():
    export = json.loads((LAB/'approved/full_icons.json').read_text(encoding='utf-8-sig'))
    catalog = json.loads((LAB/'approved/source-catalog.json').read_text(encoding='utf-8-sig'))
    assert export['catalog_fingerprint'] == catalog['fingerprint']
    assets = {a['id']: a for a in catalog['assets'] + export['imported_assets']}
    entries = {e['id']: e for e in catalog['entries']}
    assert set(export['assignments']) == set(entries) and all(export['assignments'].values())
    rows = {}
    folders = {'Skills': 'skills', 'Talents': 'talents', 'Defensive Mechanics': 'mechanics', 'Enemy Statuses': 'statuses'}
    for key, e in entries.items():
        if key in BUFF_SOURCES:
            continue
        a = assets[export['assignments'][key]]
        raw = base64.b64decode(a['data_url'].split(',', 1)[1]) if a.get('kind') != 'existing' and 'data_url' in a else (LAB/a['url']).read_bytes()
        assert hashlib.sha256(raw).hexdigest() == a['sha256'], key
        name = re.sub(r'[^a-z0-9]+', '_', e['name'].lower()).strip('_')
        folder = folders[e['category']] + ('/'+e['tree'].lower() if e['category'] == 'Talents' else '')
        relative = f'assets/ui/assigned/{folder}/{name}.png'
        target = ROOT/'project'/relative
        target.parent.mkdir(parents=True, exist_ok=True)
        with Image.open(io.BytesIO(raw)) as im:
            im = im.convert('RGBA')
            assert im.width == im.height, key
            im.resize((32, 32), Image.Resampling.NEAREST).save(target)
        rows[key] = {'name': e['name'], 'category': e['category'], 'path': 'res://'+relative,
                     'source_asset_id': a['id'], 'source_sha256': a['sha256'],
                     'sha256': hashlib.sha256(target.read_bytes()).hexdigest()}
    for key, source in BUFF_SOURCES.items():
        rows[key] = {'name': entries[key]['name'], 'category': 'Player Buffs', 'inherits': source,
                     'path': rows[source]['path'], 'source_asset_id': rows[source]['source_asset_id'],
                     'sha256': rows[source]['sha256']}
    supplemental = json.loads((LAB/'approved/supplemental-icons.json').read_text(encoding='utf-8'))
    for key, row in supplemental.items():
        assert key not in rows
        assert hashlib.sha256((ROOT/'project'/row['path'].removeprefix('res://')).read_bytes()).hexdigest() == row['sha256']
        rows[key] = row
    treatment = apply_treatment(rows)
    manifest = {'treatment': treatment, 'schema_version': 1, 'source_export': 'tools/icon-lab/approved/full_icons.json',
                'source_export_sha256': hashlib.sha256((LAB/'approved/full_icons.json').read_bytes()).hexdigest(),
                'buff_policy': 'Buffs inherit the granting skill or talent icon. Precision follows Precision Attacks. Greed uses the user-supplied gold icon.',
                'entries': rows}
    output = ROOT/'project/data/ui/icon_assignments.json'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
    # Explicit preloads keep all icons reachable in exported Godot builds.
    lines = ['# Generated by tools/icon-lab/install-approved-icons.py.', 'extends RefCounted', '', 'const TEXTURES := {']
    lines += [f'\t"{k}": preload("{v["path"]}"),' for k,v in rows.items() if k not in BUFF_SOURCES]
    lines += ['}', '', 'const BUFF_SOURCES := '+json.dumps(BUFF_SOURCES, indent=4), '']
    (ROOT/'project/scripts/ui/assigned_icon_data.gd').write_text('\n'.join(lines), encoding='utf-8')
    print(f'Installed {len(rows)} mappings, {len(rows)-len(BUFF_SOURCES)} named PNGs, {len(BUFF_SOURCES)} inherited buffs.')

if __name__ == '__main__':
    main()
